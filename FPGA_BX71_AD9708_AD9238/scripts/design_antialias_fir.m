clearvars;

Fs = 50e6;
Fpass = 500e3;
Fstop = 1e6;
Rp = 0.02;
Rs = 52;
M = 25;
transBw = Fstop - Fpass;
transPct = 100 * transBw / Fs;
Mmax = floor(Fs / (2 * Fstop));

fprintf("SPEC Fs=%.0f Fpass=%.0f Fstop=%.0f Rp=%.3f Rs=%.1f\n", ...
    Fs, Fpass, Fstop, Rp, Rs);
fprintf("PLAN trans_bw=%.0fHz trans_pct=%.3f%% M_max=%d\n", ...
    transBw, transPct, Mmax);

dSingle = designfilt("lowpassfir", ...
    PassbandFrequency=Fpass, ...
    StopbandFrequency=Fstop, ...
    PassbandRipple=Rp, ...
    StopbandAttenuation=Rs + 3, ...
    SampleRate=Fs, ...
    DesignMethod="equiripple");

b = double(dSingle.Numerator(:).');
order = filtord(dSingle);
numTaps = numel(b);
numFreq = 2^20;
[H, f] = freqz(b, 1, numFreq, Fs);
passMask = f <= Fpass;
stopMask = f >= Fstop;
passDb = 20 * log10(max(abs(H(passMask)), realmin));
stopDb = 20 * log10(max(abs(H(stopMask)), realmin));
passRippleDb = max(passDb) - min(passDb);
passWorstDb = max(abs(passDb));
stopAttenDb = -max(stopDb);

fprintf("SINGLE order=%d taps=%d symmetric_error=%.3e\n", ...
    order, numTaps, max(abs(b - fliplr(b))));
fprintf("SINGLE pass_ripple=%.6fdB pass_worst=%.6fdB stop=%.3fdB delay=%.3fsamples\n", ...
    passRippleDb, passWorstDb, stopAttenDb, order / 2);
fprintf("SINGLE fullrate_symmetric_multipliers=%d polyphase_MPIS=%.3f\n", ...
    ceil(numTaps / 2), numTaps / M);

fracBitsList = 16:22;
bestFracBits = 0;
for fracBits = fracBitsList
    scale = 2^fracBits;
    q = round(b * scale);
    if mod(numTaps, 2) == 1
        center = (numTaps + 1) / 2;
        q(center) = q(center) + (scale - sum(q));
    end
    bq = q / scale;
    [Hq, fq] = freqz(bq, 1, numFreq, Fs);
    passQ = 20 * log10(max(abs(Hq(fq <= Fpass)), realmin));
    stopQ = 20 * log10(max(abs(Hq(fq >= Fstop)), realmin));
    rippleQ = max(passQ) - min(passQ);
    worstQ = max(abs(passQ));
    attenQ = -max(stopQ);
    fprintf("QUANT Q%d taps=%d sum=%d ripple=%.6fdB pass_worst=%.6fdB stop=%.3fdB maxcoef=%d\n", ...
        fracBits, numTaps, sum(q), rippleQ, worstQ, attenQ, max(abs(q)));
    if bestFracBits == 0 && rippleQ <= Rp && attenQ >= Rs
        bestFracBits = fracBits;
    end
end
fprintf("QUANT selected_fraction_bits=%d\n", bestFracBits);

try
    Hspec = fdesign.lowpass(Fpass / (Fs / 2), Fstop / (Fs / 2), Rp, Rs);
    ifirSys = ifir(Hspec, SystemObject=true);
    ifirCost = cost(ifirSys);
    fprintf("IFIR MPIS=%.3f states=%d\n", ...
        ifirCost.MultiplicationsPerInputSample, ifirCost.NumStates);
catch exception
    fprintf("IFIR unavailable: %s\n", exception.message);
    ifirSys = [];
end

selectedFracBits = 16;
selectedScale = 2^selectedFracBits;
qSelected = round(b * selectedScale);
center = (numTaps + 1) / 2;
qSelected(center) = qSelected(center) + ...
    (selectedScale - sum(qSelected));
bSelected = qSelected / selectedScale;
[Hselected, fSelected] = freqz(bSelected, 1, numFreq, Fs);
passSelected = 20 * log10(max(abs(Hselected(fSelected <= Fpass)), realmin));
stopSelected = 20 * log10(max(abs(Hselected(fSelected >= Fstop)), realmin));
selectedRipple = max(passSelected) - min(passSelected);
selectedStop = -max(stopSelected);
assert(numTaps == 307, "Unexpected FIR tap count; inspect MATLAB/toolbox drift.");
assert(max(abs(qSelected - fliplr(qSelected))) == 0, ...
    "Quantized coefficients lost symmetry.");
assert(sum(qSelected) == selectedScale, "Quantized DC gain is not unity.");
assert(selectedRipple <= Rp, "Quantized passband ripple missed the spec.");
assert(selectedStop >= Rs, "Quantized stopband attenuation missed the spec.");

scriptDir = fileparts(mfilename("fullpath"));
fpgaRoot = fileparts(scriptDir);
verilogPath = fullfile(fpgaRoot, "rtl", "fir307_antialias_coeffs.vh");
cHeaderPath = fullfile(fpgaRoot, "..", "STM32H743_AD9238", ...
    "DSP", "ad9238_fir307_coeffs.h");

verilogFile = fopen(verilogPath, "w");
assert(verilogFile >= 0, "Unable to create Verilog coefficient include.");
verilogCleanup = onCleanup(@() fclose(verilogFile));
fprintf(verilogFile, ...
    "/* Generated by scripts/design_antialias_fir.m; Q16, first half plus center. */\n");
for index = 1:center
    coefficient = qSelected(index);
    if coefficient < 0
        fprintf(verilogFile, ...
            "8'd%d: FIR307_Coefficient = -18'sd%d;\n", ...
            index - 1, -coefficient);
    else
        fprintf(verilogFile, ...
            "8'd%d: FIR307_Coefficient = 18'sd%d;\n", ...
            index - 1, coefficient);
    end
end
fprintf(verilogFile, "default: FIR307_Coefficient = 18'sd0;\n");
clear verilogCleanup;

cHeaderFile = fopen(cHeaderPath, "w");
assert(cHeaderFile >= 0, "Unable to create C coefficient header.");
cHeaderCleanup = onCleanup(@() fclose(cHeaderFile));
fprintf(cHeaderFile, ...
    "#ifndef AD9238_FIR307_COEFFS_H\n#define AD9238_FIR307_COEFFS_H\n\n");
fprintf(cHeaderFile, "#include <stdint.h>\n\n");
fprintf(cHeaderFile, "#define AD9238_FIR307_TAP_COUNT 307U\n");
fprintf(cHeaderFile, "#define AD9238_FIR307_CENTER_INDEX 153U\n");
fprintf(cHeaderFile, "#define AD9238_FIR307_COEFF_FRACTION_BITS 16U\n");
fprintf(cHeaderFile, "#define AD9238_FIR307_GROUP_DELAY_SAMPLES 153.0f\n\n");
fprintf(cHeaderFile, ...
    "static const int16_t g_ad9238_fir307_half_coeff_q16[154] = {\n    ");
for index = 1:center
    if index < center
        if mod(index, 8) == 0
            fprintf(cHeaderFile, "%d,\n    ", qSelected(index));
        else
            fprintf(cHeaderFile, "%d, ", qSelected(index));
        end
    else
        fprintf(cHeaderFile, "%d\n", qSelected(index));
    end
end
fprintf(cHeaderFile, "};\n\n#endif /* AD9238_FIR307_COEFFS_H */\n");
clear cHeaderCleanup;

fprintf("GENERATED %s\n", verilogPath);
fprintf("GENERATED %s\n", cHeaderPath);

try
    singleSys = dsp.FIRFilter(Numerator=b);
    if isempty(ifirSys)
        filterAnalyzer(singleSys, FilterNames="Single_Stage_FIR", ...
            SampleRates=Fs, Analysis="magnitude", OverlayAnalysis="phase");
    else
        filterAnalyzer(singleSys, ifirSys, ...
            FilterNames=["Single_Stage_FIR", "IFIR"], ...
            SampleRates=Fs, Analysis="magnitude", OverlayAnalysis="phase");
    end
    fprintf("FILTER_ANALYZER_OPENED\n");
catch exception
    fprintf("FILTER_ANALYZER unavailable: %s\n", exception.message);
end
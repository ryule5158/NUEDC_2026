#define DEBUG_UART1_TX_BUFFER_SIZE 32768U

static uint8_t s_debug_uart1_tx_buffer[DEBUG_UART1_TX_BUFFER_SIZE];
static volatile uint32_t s_debug_uart1_tx_head;
static volatile uint32_t s_debug_uart1_tx_tail;
static volatile uint16_t s_debug_uart1_tx_active_length;
static volatile uint8_t s_debug_uart1_tx_active;
static volatile uint32_t s_debug_uart1_tx_dropped;

/*
 * 调用者必须保证本函数不会与 DebugUart1_TxComplete 并发执行。
 * 一次尽量提交连续的一整段，避免每个 printf 字符都单独启动发送。
 */
static void DebugUart1_StartLocked(void)
{
  uint32_t length;

  if ((s_debug_uart1_tx_active != 0U) ||
      (s_debug_uart1_tx_head == s_debug_uart1_tx_tail)) {
    return;
  }
  if (s_debug_uart1_tx_head > s_debug_uart1_tx_tail) {
    length = s_debug_uart1_tx_head - s_debug_uart1_tx_tail;
  } else {
    length = DEBUG_UART1_TX_BUFFER_SIZE - s_debug_uart1_tx_tail;
  }

  s_debug_uart1_tx_active_length = (uint16_t)length;
  s_debug_uart1_tx_active = 1U;
  if (HAL_UART_Transmit_IT(
          &huart1,
          &s_debug_uart1_tx_buffer[s_debug_uart1_tx_tail],
          (uint16_t)length) != HAL_OK) {
    s_debug_uart1_tx_active = 0U;
    s_debug_uart1_tx_active_length = 0U;
  }
}

static uint8_t DebugUart1_QueueByte(uint8_t data)
{
  uint32_t next;
  uint32_t primask = __get_PRIMASK();

  __disable_irq();
  next = s_debug_uart1_tx_head + 1U;
  if (next >= DEBUG_UART1_TX_BUFFER_SIZE) next = 0U;
  if (next == s_debug_uart1_tx_tail) {
    s_debug_uart1_tx_dropped++;
    if (primask == 0U) __enable_irq();
    return 0U;
  }

  s_debug_uart1_tx_buffer[s_debug_uart1_tx_head] = data;
  s_debug_uart1_tx_head = next;
  DebugUart1_StartLocked();
  if (primask == 0U) __enable_irq();
  return 1U;
}

static int DebugUart1_PutChar(int ch)
{
  uint8_t data = (uint8_t)ch;

  /*
   * 主程序中的 printf 只入队，不等待 115200 baud 的线速。异常处理
   * 或关中断区无法依赖 TX 中断，保留原来的阻塞发送作为诊断退路。
   */
  if ((__get_IPSR() != 0U) || (__get_PRIMASK() != 0U)) {
    (void)HAL_UART_Transmit(&huart1, &data, 1U, 0xFFFFU);
  } else {
    (void)DebugUart1_QueueByte(data);
  }
  return ch;
}

int fputc(int ch, FILE *f)
{
  (void)f;
  return DebugUart1_PutChar(ch);
}

int __io_putchar(int ch)
{
  return DebugUart1_PutChar(ch);
}

void DebugUart1_TxComplete(UART_HandleTypeDef *huart)
{
  if ((huart != &huart1) &&
      ((huart == NULL) || (huart->Instance != USART1))) {
    return;
  }

  if (s_debug_uart1_tx_active != 0U) {
    uint32_t next = s_debug_uart1_tx_tail +
                    (uint32_t)s_debug_uart1_tx_active_length;
    if (next >= DEBUG_UART1_TX_BUFFER_SIZE) {
      next -= DEBUG_UART1_TX_BUFFER_SIZE;
    }
    s_debug_uart1_tx_tail = next;
  }
  s_debug_uart1_tx_active = 0U;
  s_debug_uart1_tx_active_length = 0U;
  DebugUart1_StartLocked();
}

uint32_t DebugUart1_GetPendingByteCount(void)
{
  uint32_t head;
  uint32_t tail;
  uint32_t primask = __get_PRIMASK();

  __disable_irq();
  head = s_debug_uart1_tx_head;
  tail = s_debug_uart1_tx_tail;
  if (primask == 0U) __enable_irq();
  return (head + DEBUG_UART1_TX_BUFFER_SIZE - tail) %
         DEBUG_UART1_TX_BUFFER_SIZE;
}

uint32_t DebugUart1_GetDroppedByteCount(void)
{
  return s_debug_uart1_tx_dropped;
}

